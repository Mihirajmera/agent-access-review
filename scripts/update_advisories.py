"""Refresh agent_access_review/advisories.yaml from OSV (https://osv.dev), the snapshot AAR-14 checks.

    python scripts/update_advisories.py

Every npm and PyPI package named in catalog.yaml is queried, plus a few MCP packages that are
not servers in their own right but run in agent configs (EXTRA). Scans stay offline and
reproducible because they read the snapshot, never the network.
"""
from __future__ import annotations

import json
import urllib.request
from datetime import date
from pathlib import Path

import yaml

PKG = Path(__file__).resolve().parent.parent / 'agent_access_review'
EXTRA = [('npm', 'mcp-remote')]       # stdio-to-remote bridge, CVE-2025-6514
SEVERITY = {'CRITICAL': 'critical', 'HIGH': 'high', 'MODERATE': 'medium', 'MEDIUM': 'medium', 'LOW': 'low'}


def packages() -> list[tuple[str, str]]:
    servers = yaml.safe_load((PKG / 'catalog.yaml').read_text(encoding='utf-8'))['servers']
    out = []
    for name, profile in servers.items():
        for n in [name, *profile.get('aliases', [])]:
            if '/' in n and not n.startswith('@'):
                continue                     # a container image, not a package
            # Unscoped names can exist on both registries -- sometimes as different software.
            out += [('npm', n)] if n.startswith('@') else [('PyPI', n), ('npm', n)]
    return sorted(set(out + EXTRA))


def query(eco: str, name: str) -> list[dict]:
    body = json.dumps({'package': {'name': name, 'ecosystem': eco}}).encode()
    req = urllib.request.Request('https://api.osv.dev/v1/query', body, {'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r).get('vulns', [])


def entry(v: dict, eco: str, name: str) -> dict | None:
    ranges = []
    for a in v.get('affected', []):
        if a['package']['ecosystem'] != eco or a['package']['name'].lower() != name.lower():
            continue
        for r in a.get('ranges', []):
            if r['type'] != 'ECOSYSTEM' and r['type'] != 'SEMVER':
                continue
            cur = None
            for e in r['events']:
                if 'introduced' in e:
                    cur = {'introduced': e['introduced']}
                    ranges.append(cur)
                elif cur is not None:
                    cur.update(e)            # fixed or last_affected closes the range
    if not ranges:
        return None
    malicious = v['id'].startswith('MAL-')
    sev = 'critical' if malicious else SEVERITY.get((v.get('database_specific') or {}).get('severity', ''), 'medium')
    out = {'id': v['id'], 'severity': sev, 'ranges': ranges,
           'summary': ' '.join(v.get('summary', '').split())[:160]}
    cves = [a for a in v.get('aliases', []) if a.startswith('CVE-')]
    if cves:
        out['cve'] = cves[0]
    if malicious:
        out['malicious'] = True
    return out


def main() -> None:
    result = {}
    for eco, name in packages():
        entries = [e for v in query(eco, name) if (e := entry(v, eco, name))]
        # PyPI advisories appear twice (GHSA and PYSEC); keep the GHSA copy.
        seen = {e['cve'] for e in entries if 'cve' in e and e['id'].startswith('GHSA-')}
        entries = [e for e in entries if not (e['id'].startswith('PYSEC-') and e.get('cve') in seen)]
        if entries:
            result[f'{eco}:{name}'] = sorted(entries, key=lambda e: e['id'])
    header = ('# Known advisories for MCP server packages, from OSV. Generated by\n'
              '# scripts/update_advisories.py; do not edit by hand. Used by AAR-14.\n')
    doc = {'as_of': date.today().isoformat(), 'source': 'https://osv.dev', 'packages': result}
    (PKG / 'advisories.yaml').write_text(header + yaml.safe_dump(doc, sort_keys=False, width=120),
                                         encoding='utf-8')
    print(f'{sum(map(len, result.values()))} advisories for {len(result)} packages')


if __name__ == '__main__':
    main()
